// CatalogRepository over the real API (catalog module: catalog.controller.ts). The official Método 180 catalog:
// everyone reads the active entries, only SM Global edits, and every edit applies to new programs only. The shapes
// are the front's own (CatalogAdminItem, CatalogChange), so the answers pass through unchanged.
import type { CatalogRepository } from "../repositories";
import type { CatalogAdminItem, CatalogChange } from "../types";
import type { HttpClient } from "./client";

const itemPath = (code: string) => `/catalog/${encodeURIComponent(code)}`;

export function createHttpCatalogRepository(client: HttpClient): CatalogRepository {
  return {
    /** Archived entries only on request (and only for SM Global; the API ignores it for everyone else). */
    list: (opts) =>
      client.get<CatalogAdminItem[]>("/catalog", {
        query: { include_archived: opts?.include_archived ? "true" : undefined },
      }),

    /** The code is generated by the API (next number of the area). */
    add: (input) => client.post<CatalogAdminItem>("/catalog", input),

    /** Any subset of the fields (the area cannot change: area_locked) plus the note kept in the history. */
    update: (code, patch, note) =>
      client.patch<CatalogAdminItem>(itemPath(code), { ...patch, note: note ?? null }),

    archive: (code, reason) =>
      client.post<CatalogAdminItem>(`${itemPath(code)}/archive`, { reason }),

    restore: (code) => client.post<CatalogAdminItem>(`${itemPath(code)}/restore`),

    /** Newest first, one entry or all. SM Global only. */
    listHistory: (code) => client.get<CatalogChange[]>("/catalog/history", { query: { code } }),
  };
}
